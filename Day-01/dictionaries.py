# ============================================================
# DICTIONARIES
# ============================================================

person = {
    "name": "Alex",
    "age": 20,
    "country": "India"
}

print(person)
print(type(person))


# ------------------------------------------------------------
# ACCESS VALUE
# ------------------------------------------------------------

print(person["name"])
print(person["age"])


# ------------------------------------------------------------
# GET
# ------------------------------------------------------------

print(person.get("name"))
print(person.get("email"))

# Avoids KeyError when key doesn't exist.


# ------------------------------------------------------------
# CHANGE VALUE
# ------------------------------------------------------------

person["age"] = 21

print(person)


# ------------------------------------------------------------
# ADD VALUE
# ------------------------------------------------------------

person["email"] = "alex@example.com"

print(person)


# ------------------------------------------------------------
# REMOVE
# ------------------------------------------------------------

person.pop("email")

print(person)


# popitem removes the last item

person.popitem()

print(person)


# ------------------------------------------------------------
# KEYS
# ------------------------------------------------------------

print(person.keys())


# ------------------------------------------------------------
# VALUES
# ------------------------------------------------------------

print(person.values())


# ------------------------------------------------------------
# ITEMS
# ------------------------------------------------------------

print(person.items())


# ------------------------------------------------------------
# LOOP
# ------------------------------------------------------------

for key in person:
    print(key)


for key, value in person.items():
    print(key, value)


# ------------------------------------------------------------
# CHECK KEY
# ------------------------------------------------------------

print("name" in person)


# ------------------------------------------------------------
# NESTED DICTIONARY
# ------------------------------------------------------------

student = {
    "name": "Alex",
    "marks": {
        "python": 90,
        "math": 85
    }
}

print(student["marks"]["python"])
