# ============================================================
# LISTS
# ============================================================


numbers = [1, 2, 3, 4, 5]

print(numbers)
print(type(numbers))


# ------------------------------------------------------------
# INDEXING
# ------------------------------------------------------------

print(numbers[0])
print(numbers[-1])


# ------------------------------------------------------------
# SLICING
# ------------------------------------------------------------

print(numbers[1:4])
print(numbers[:3])
print(numbers[2:])
print(numbers[::-1])


# ------------------------------------------------------------
# CHANGE ELEMENT
# ------------------------------------------------------------

numbers[0] = 100

print(numbers)


# ------------------------------------------------------------
# APPEND
# ------------------------------------------------------------

numbers.append(6)

print(numbers)


# ------------------------------------------------------------
# INSERT
# ------------------------------------------------------------

numbers.insert(1, 200)

print(numbers)


# ------------------------------------------------------------
# EXTEND
# ------------------------------------------------------------

numbers.extend([7, 8, 9])

print(numbers)


# ------------------------------------------------------------
# REMOVE
# ------------------------------------------------------------

numbers.remove(200)

print(numbers)


# ------------------------------------------------------------
# POP
# ------------------------------------------------------------

last = numbers.pop()

print(last)
print(numbers)


# Remove using index

numbers.pop(0)

print(numbers)


# ------------------------------------------------------------
# CLEAR
# ------------------------------------------------------------

numbers.clear()

print(numbers)


# ------------------------------------------------------------
# COUNT
# ------------------------------------------------------------

numbers = [1, 2, 2, 3, 2, 4]

print(numbers.count(2))


# ------------------------------------------------------------
# INDEX
# ------------------------------------------------------------

print(numbers.index(3))


# ------------------------------------------------------------
# SORT
# ------------------------------------------------------------

numbers.sort()

print(numbers)

numbers.sort(reverse=True)

print(numbers)


# ------------------------------------------------------------
# REVERSE
# ------------------------------------------------------------

numbers.reverse()

print(numbers)


# ------------------------------------------------------------
# COPY
# ------------------------------------------------------------

original = [1, 2, 3]

copy_list = original.copy()

print(copy_list)


# ------------------------------------------------------------
# LENGTH
# ------------------------------------------------------------

print(len(numbers))


# ------------------------------------------------------------
# MEMBERSHIP
# ------------------------------------------------------------

print(2 in numbers)
print(10 not in numbers)


# ------------------------------------------------------------
# LOOP THROUGH LIST
# ------------------------------------------------------------

for item in numbers:
    print(item)


# ------------------------------------------------------------
# LIST WITH DIFFERENT DATA TYPES
# ------------------------------------------------------------

data = [10, 3.14, "Python", True, [1, 2]]

print(data)


# ------------------------------------------------------------
# NESTED LIST
# ------------------------------------------------------------

matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]

print(matrix[0])
print(matrix[0][0])
print(matrix[1][2])


# ------------------------------------------------------------
# LIST COMPREHENSION
# ------------------------------------------------------------

numbers = [1, 2, 3, 4, 5]

squares = [x ** 2 for x in numbers]

print(squares)


even = [x for x in numbers if x % 2 == 0]

print(even)
