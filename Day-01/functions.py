# ============================================================
# FUNCTIONS
# ============================================================


# ------------------------------------------------------------
# BASIC FUNCTION
# ------------------------------------------------------------

def hello():
    print("Hello")


hello()


# ------------------------------------------------------------
# PARAMETER
# ------------------------------------------------------------

def greet(name):
    print(f"Hello {name}")


greet("Alex")
greet("Python")


# ------------------------------------------------------------
# MULTIPLE PARAMETERS
# ------------------------------------------------------------

def add(a, b):
    print(a + b)


add(10, 20)


# ------------------------------------------------------------
# RETURN
# ------------------------------------------------------------

def add(a, b):
    return a + b


result = add(10, 20)

print(result)


# ------------------------------------------------------------
# DEFAULT PARAMETER
# ------------------------------------------------------------

def greet(name="Friend"):
    print(f"Hello {name}")


greet()
greet("Alex")


# ------------------------------------------------------------
# KEYWORD ARGUMENT
# ------------------------------------------------------------

def person(name, age):
    print(name)
    print(age)


person(age=20, name="Alex")


# ------------------------------------------------------------
# *ARGS
# ------------------------------------------------------------

def add_all(*numbers):

    total = 0

    for number in numbers:
        total += number

    return total


print(add_all(1, 2, 3, 4, 5))


# ------------------------------------------------------------
# **KWARGS
# ------------------------------------------------------------

def information(**data):

    for key, value in data.items():
        print(key, value)


information(
    name="Alex",
    age=20,
    country="India"
)


# ------------------------------------------------------------
# LAMBDA
# ------------------------------------------------------------

square = lambda x: x ** 2

print(square(5))


# ------------------------------------------------------------
# FUNCTION + IF
# ------------------------------------------------------------

def check_even(number):

    if number % 2 == 0:
        return True

    return False


print(check_even(10))
print(check_even(7))
