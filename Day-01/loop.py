# ============================================================
# FOR LOOP
# ============================================================

numbers = [1, 2, 3, 4, 5]

for number in numbers:
    print(number)


# ------------------------------------------------------------
# RANGE
# ------------------------------------------------------------

for i in range(5):
    print(i)


for i in range(1, 6):
    print(i)


for i in range(0, 10, 2):
    print(i)


# ------------------------------------------------------------
# STRING LOOP
# ------------------------------------------------------------

word = "Python"

for character in word:
    print(character)


# ------------------------------------------------------------
# ENUMERATE
# ------------------------------------------------------------

names = ["Alex", "John", "Sam"]

for index, name in enumerate(names):
    print(index, name)


# ------------------------------------------------------------
# WHILE LOOP
# ------------------------------------------------------------

count = 0

while count < 5:
    print(count)
    count += 1


# ------------------------------------------------------------
# BREAK
# ------------------------------------------------------------

for i in range(10):

    if i == 5:
        break

    print(i)


# ------------------------------------------------------------
# CONTINUE
# ------------------------------------------------------------

for i in range(10):

    if i == 5:
        continue

    print(i)


# ------------------------------------------------------------
# PASS
# ------------------------------------------------------------

for i in range(5):

    if i == 3:
        pass

    print(i)
