# ============================================================
# SETS
# ============================================================

numbers = {1, 2, 3, 4, 5}

print(numbers)
print(type(numbers))


# Sets automatically remove duplicates

numbers = {1, 2, 2, 3, 3, 4}

print(numbers)


# ------------------------------------------------------------
# ADD
# ------------------------------------------------------------

numbers.add(5)

print(numbers)


# ------------------------------------------------------------
# UPDATE
# ------------------------------------------------------------

numbers.update([6, 7, 8])

print(numbers)


# ------------------------------------------------------------
# REMOVE
# ------------------------------------------------------------

numbers.remove(8)

print(numbers)


# discard does not give an error
# if the value does not exist.

numbers.discard(100)


# ------------------------------------------------------------
# POP
# ------------------------------------------------------------

numbers.pop()

print(numbers)


# ------------------------------------------------------------
# SET OPERATIONS
# ------------------------------------------------------------

a = {1, 2, 3, 4}
b = {3, 4, 5, 6}

print(a | b)    # Union
print(a & b)    # Intersection
print(a - b)    # Difference
print(a ^ b)    # Symmetric difference


# ------------------------------------------------------------
# MEMBERSHIP
# ------------------------------------------------------------

print(3 in a)
print(10 not in a)
