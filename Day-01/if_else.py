# ============================================================
# IF / ELIF / ELSE
# ============================================================

age = 20

if age >= 18:
    print("Adult")
else:
    print("Minor")


# ------------------------------------------------------------
# ELIF
# ------------------------------------------------------------

marks = 85

if marks >= 90:
    print("A+")
elif marks >= 80:
    print("A")
elif marks >= 70:
    print("B")
else:
    print("Needs improvement")


# ------------------------------------------------------------
# NESTED IF
# ------------------------------------------------------------

age = 20
has_id = True

if age >= 18:
    if has_id:
        print("Allowed")
    else:
        print("ID required")
else:
    print("Not allowed")


# ------------------------------------------------------------
# TERNARY
# ------------------------------------------------------------

age = 20

result = "Adult" if age >= 18 else "Minor"

print(result)
